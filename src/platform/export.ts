import type { DatasetMeta } from '@/core/model/types';
import type { RangeStats } from '@/core/stats/rangeStats';
import { formatDateShort, formatPct, formatPrice, formatSigned } from '@/render/format';

/** A file name safe on every OS ("EUR/USD" → "EUR-USD"). */
export function safeFileName(name: string): string {
  return name.replace(/[\\/:*?"<>|\u0000-\u001f]+/g, '-').replace(/^[.\s]+|[.\s]+$/g, '') || 'chart';
}

export function downloadUrl(url: string, fileName: string): void {
  const a = document.createElement('a');
  a.href = url;
  a.download = safeFileName(fileName);
  document.body.appendChild(a);
  a.click();
  a.remove();
}

export function downloadText(text: string, fileName: string, mime = 'text/csv'): void {
  const url = URL.createObjectURL(new Blob([text], { type: mime }));
  downloadUrl(url, fileName);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function imageSize(dataUrl: string): Promise<{ w: number; h: number }> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve({ w: img.naturalWidth, h: img.naturalHeight });
    img.onerror = reject;
    img.src = dataUrl;
  });
}

export interface PdfInput {
  title: string;
  subtitle: string;
  settings: string[];
  image: string;
  meta: DatasetMeta;
  stats: RangeStats | null;
  notes: string[];
}

/** One-page landscape PDF: vector text + raster chart image. */
export async function exportPdf(input: PdfInput, fileName: string): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();
  const M = 36;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text(input.title, M, M + 8);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(107, 111, 120);
  doc.text(input.subtitle, M, M + 26);
  doc.text(input.settings.join('  ·  '), M, M + 40);

  const { w, h } = await imageSize(input.image);
  const imgW = W - 2 * M;
  const imgH = Math.min(330, (imgW * h) / w);
  doc.addImage(input.image, 'PNG', M, M + 52, imgW, imgH, undefined, 'FAST');

  let y = M + 52 + imgH + 24;
  const p = input.meta.precision;
  if (input.stats) {
    const s = input.stats;
    const rows: [string, string][] = [
      ['Range', `${formatDateShort(s.from)} – ${formatDateShort(s.to)} (${s.bars} complete bars)`],
      ['Change', `${formatSigned(s.change, p)} (${formatPct(s.changePct)})`],
      ['High / Low', `${formatPrice(s.high, p)} (${formatDateShort(s.highTime)}) / ${formatPrice(s.low, p)} (${formatDateShort(s.lowTime)})`],
      ['CAGR', s.cagr === null ? '— (under 1 year)' : formatPct(s.cagr)],
      ['Volatility (annualised)', s.volatility === null ? '—' : formatPct(s.volatility, 1, false)],
      ['Max drawdown', `${formatPct(s.maxDrawdown, 1)}${s.maxDrawdown < 0 ? ` (${formatDateShort(s.drawdownPeakTime)} → ${formatDateShort(s.drawdownTroughTime)})` : ''}`],
    ];
    doc.setTextColor(27, 29, 34);
    doc.setFontSize(10);
    const colW = (W - 2 * M) / 2;
    rows.forEach(([k, v], i) => {
      const x = M + (i % 2) * colW;
      const yy = y + Math.floor(i / 2) * 16;
      doc.setFont('helvetica', 'bold');
      doc.text(k, x, yy);
      doc.setFont('helvetica', 'normal');
      doc.text(v, x + 130, yy);
    });
    y += Math.ceil(rows.length / 2) * 16 + 8;
  }
  doc.setFontSize(8);
  doc.setTextColor(107, 111, 120);
  for (const n of input.notes.slice(0, 4)) {
    // Wrap long notes to the page width.
    const lines = doc.splitTextToSize(`• ${n}`, W - 2 * M) as string[];
    doc.text(lines, M, y);
    y += 11 * lines.length;
  }
  doc.text(`Generated by FinAInce on ${new Date().toISOString().slice(0, 10)}. Charts rendered with KLineChart (Apache-2.0).`, M, doc.internal.pageSize.getHeight() - 20);
  doc.save(fileName);
}
